def qlabel(date):
    y, m, _ = date.split("-")
    return {"03": f"{y}Q1", "06": f"{y}H1", "09": f"{y}Q1-Q3", "12": f"{y}A"}[m]


def yoy_change(rows, i, field):
    d = dt.date.fromisoformat(rows[i]["report_date"])
    target = f"{d.year-1}-{d.month:02d}-{d.day:02d}"
    prior = next((r for r in rows if r["report_date"] == target), None)
    try:
        now, old = float(rows[i][field]), float(prior[field])
        if old == 0:
            return "不可比"
        return pct((now / old - 1) * 100, signed=True)
    except (TypeError, ValueError, KeyError):
        return "—"


def event_class(rows, i):
    r = rows[i]
    try:
        npy = float(r["net_profit_yoy_pct"])
    except ValueError:
        npy = 0
    try:
        rr = float(r["ret_20d_pct"])
    except ValueError:
        rr = 0
    try:
        ocf = float(r["ocf_cny"])
    except ValueError:
        ocf = 0
    prev_npy = None
    if i:
        try:
            prev_npy = float(rows[i - 1]["net_profit_yoy_pct"])
        except ValueError:
            pass
    if npy < 0 or ocf < 0:
        return "盈利、现金流或利润率出现实质拐点"
    if npy >= 50 and rr >= 3:
        return "业绩高增、价格反应指向预期继续上修*"
    if npy >= 50 and rr <= -3:
        return "业绩仍高增但利好兑现/估值压缩*"
    if prev_npy is not None and npy > 20 and prev_npy - npy >= 25:
        return "业绩仍高增但边际放缓"
    if npy <= 20 and rr >= 5:
        return "业绩平淡但远期预期上修*"
    if npy > 0 and rr <= -8:
        return "估值压缩主导，而非业绩恶化主导"
    return "业绩与价格反应均未形成单一主导"


