def fnum(x, digits=1, missing="未披露"):
    try:
        v = float(x)
        if not math.isfinite(v):
            return missing
        return f"{v:,.{digits}f}"
    except (TypeError, ValueError):
        return missing


def pct(x, digits=1, signed=False, missing="—"):
    try:
        v = float(x)
        sign = "+" if signed and v > 0 else ""
        return f"{sign}{v:.{digits}f}%"
    except (TypeError, ValueError):
        return missing


def yi(x, digits=1, missing="—"):
    try:
        return f"{float(x)/1e8:,.{digits}f}"
    except (TypeError, ValueError):
        return missing


def pe(x):
    try:
        v = float(x)
        return "亏损/PE失真" if v <= 0 else f"{v:.1f}×"
    except (TypeError, ValueError):
        return "未取到"


def md_table(headers, rows):
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join(["---"] * len(headers)) + "|"]
    out.extend("| " + " | ".join(str(c).replace("\n", "<br>") for c in row) + " |" for row in rows)
    return "\n".join(out)


